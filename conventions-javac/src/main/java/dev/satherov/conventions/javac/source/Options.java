package dev.satherov.conventions.javac.source;

import org.jetbrains.annotations.Unmodifiable;

import java.io.File;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

///
/// The options a project passes after `-Xplugin:Conventions`, each as `key=value`.
///
/// - `root`: the root package of the project, which makes its own import group.
/// - `set`: `main` or `test`, the source set being compiled.
/// - `disable`: comma-separated ids of the rules that do not run.
/// - `generated`: the directories of the project's own generated sources, separated by the platform path separator.
/// - `skip`: the directories of sources no rule looks at, such as the output of annotation processors.
///
/// @param root      The root package of the project, or an empty string if none was given.
/// @param set       The source set being compiled.
/// @param disabled  Any ids of rules that do not run.
/// @param generated Any directories whose sources are generated by the project itself.
/// @param skipped   Any directories whose sources no rule looks at.
///
public record Options(
        String root,
        SourceSet set,
        @Unmodifiable Set<String> disabled,
        @Unmodifiable List<Path> generated,
        @Unmodifiable List<Path> skipped
) {

    ///
    /// Copies the collections, so that the options cannot change afterwards.
    ///
    public Options {
        disabled = Set.copyOf(disabled);
        generated = List.copyOf(generated);
        skipped = List.copyOf(skipped);
    }

    ///
    /// Reads the options from the arguments javac passes to the plugin.
    ///
    /// @param args The arguments, each `key=value`.
    ///
    /// @return The options, with the main source set and no root package where the arguments name none.
    ///
    /// @throws IllegalArgumentException - If an argument has no `=`.
    /// - If an argument has an unknown key.
    /// - If `set` is neither `main` nor `test`.
    ///
    public static Options from(String... args) {
        String root = "";
        SourceSet set = SourceSet.MAIN;
        Set<String> disabled = new HashSet<>();
        List<Path> generated = new ArrayList<>();
        List<Path> skipped = new ArrayList<>();
        for (String arg : args) {
            int split = arg.indexOf('=');
            if (split < 0) {
                throw new IllegalArgumentException("Conventions option without '=': " + arg);
            }

            String value = arg.substring(split + 1);
            switch (arg.substring(0, split)) {
                case "root" -> root = value;
                case "set" -> set = SourceSet.from(value);
                case "disable" -> disabled.addAll(Options.split(value, ","));
                case "generated" -> generated.addAll(Options.paths(value));
                case "skip" -> skipped.addAll(Options.paths(value));
                default -> throw new IllegalArgumentException("Unknown conventions option: " + arg);
            }
        }

        return new Options(root, set, disabled, generated, skipped);
    }

    ///
    /// Splits the given value at the given separator, without empty parts.
    ///
    private static @Unmodifiable List<String> split(String value, String separator) {
        return Arrays.stream(value.split(separator))
                .map(String::strip)
                .filter(part -> !part.isEmpty())
                .toList();
    }

    ///
    /// Reads the directories in the given value, separated by the platform path separator.
    ///
    private static @Unmodifiable List<Path> paths(String value) {
        return Options.split(value, File.pathSeparator)
                .stream()
                .map(part -> Path.of(part).toAbsolutePath().normalize())
                .toList();
    }
}
